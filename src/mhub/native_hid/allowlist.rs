pub(super) fn supported(i: &Interface) -> bool {
    let pinned = FILTERS.iter().any(|(vendor, page, usage, products)| {
        *vendor == i.vid
            && *page == i.usage_page
            && usage.is_none_or(|usage| usage == i.usage)
            && products.contains(&i.pid)
    });
    if !pinned {
        return false;
    }
    if matches!((i.vid, i.pid), (0x3554, 0xfa09) | (0x41e4, 0x2001)) {
        return match i.usage_page {
            0xff02 => i.input_len == 20 && i.output_len == 20,
            0xff04 => i.feature_len == 8,
            _ => false,
        };
    }
    // Shared OEM identifiers also occur on unrelated brands. Accept their
    // vendor collections only when the hardware identifies its MCHOSE origin.
    i.vid == 0x3837
        || i.product.trim().to_ascii_uppercase().starts_with("MCHOSE ")
        || (i.vid == 0x0bda && i.pid == 0x4762 && i.product.trim().eq_ignore_ascii_case("A5 ultra"))
}
